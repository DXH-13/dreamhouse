// Tách một tường thành các đoạn: fn(kind, từ, đến) với kind = "solid" | "door" | "glass".
export function pieces([, , a0, a1, gaps = []], fn) {
  let at = a0;
  for (const [s, e, kind] of [...gaps].sort((p, q) => p[0] - q[0])) {
    if (s > at) fn("solid", at, s);
    fn(kind, s, e);
    at = e;
  }
  if (a1 > at) fn("solid", at, a1);
}

